void UK2Node_SetWebState::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);
	CreateWebPin();

	UEdGraphPin* State = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, StateEnum.Get(), StatePinName);
	State->PinToolTip = LOCTEXT("StateTooltip", "The state to head for.").ToString();
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(State,
		StateEnum && StateEnum->NumEnums() > 1 ? StateEnum->GetNameStringByIndex(0) : TEXT("0"));

	UEdGraphPin* Instant = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, InstantPinName);
	Instant->PinToolTip = LOCTEXT("InstantTooltip", "Jump straight there, with no transition.").ToString();
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Instant, TEXT("false"));

	UEdGraphPin* Success = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Boolean, SuccessPinName);
	Success->PinToolTip = LOCTEXT("SuccessTooltip",
		"False if refused: the Web is paused or headed for a pause, or (Transition Traversal Only) no transitions lead there.").ToString();

	Super::AllocateDefaultPins();
}

void UK2Node_SetWebState::OnWebClassChanged()
{
	UEnum* NewEnum = CodeAnimWebNodes::GetStateEnum(WebClass);
	if (WebClass && NewEnum != StateEnum)
	{
		StateEnum = NewEnum;
		WebStateNodes::Retype(FindPin(StatePinName), StateEnum, /*bSetDefault*/ true);
	}
}

void UK2Node_SetWebState::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	if (WebClass)
	{
		PreloadObject(WebClass);
		StateEnum = CodeAnimWebNodes::GetStateEnum(WebClass);
	}
	Super::ReallocatePinsDuringReconstruction(OldPins);
}

