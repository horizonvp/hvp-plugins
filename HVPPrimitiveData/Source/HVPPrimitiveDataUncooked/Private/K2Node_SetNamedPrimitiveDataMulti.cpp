void UK2Node_SetNamedPrimitiveDataMulti::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UPrimitiveDataLegend* Legend = GetLegend();
	if (!Legend)
	{
		MessageLog.Error(*LOCTEXT("NoLegend", "@@ has no Primitive Data Legend chosen.").ToString(), this);
		return;
	}
	if (Selection.Num() == 0)
	{
		MessageLog.Error(*LOCTEXT("NothingTicked", "@@ sets nothing - tick its parameters in the Details panel.").ToString(), this);
		return;
	}
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (!Entry)
		{
			MessageLog.Error(*FText::Format(LOCTEXT("NoParameter", "@@: parameter '{0}' is not in {1}."),
				FText::FromName(Selected.Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (!Entry->HasSlot())
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("NoSlot", "@@: '{0}' has no slot in {1} - the legend is out of room. Open it for details."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (SetNamedPrimitiveDataMulti::KindOf(Entry) != Selected.Kind)
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("StaleKind", "@@: '{0}' changed type in {1}. Refresh the node (right-click > Refresh Nodes)."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
	}
}

void UK2Node_SetNamedPrimitiveDataMulti::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	const UPrimitiveDataLegend* Legend = GetLegend();

	// Validation says why for each of these; all that is left is to emit nothing.
	struct FWrite
	{
		const FPrimitiveDataLegendEntry* Entry;
		UEdGraphPin* Pin;
	};
	TArray<FWrite> Writes;
	bool bValid = Legend != nullptr && Selection.Num() > 0;
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		UEdGraphPin* Pin = FindValuePin(Selected.Id);
		if (!Entry || !Entry->HasSlot() || !Pin || SetNamedPrimitiveDataMulti::KindOf(Entry) != Selected.Kind)
		{
			bValid = false;
			break;
		}
		Writes.Add({ Entry, Pin });
	}
	int32 First = 0;
	int32 Count = 0;
	uint64 Mask = 0;
	if (!bValid || !GetWriteRange(First, Count, Mask))
	{
		BreakAllNodeLinks();
		return;
	}

	// Unwired Target means self: fine in a primitive component's own Blueprint, an error anywhere else.
	UEdGraphPin* Target = FindPinChecked(TargetPinName);
	if (Target->LinkedTo.Num() == 0)
	{
		const UClass* Context = CompilerContext.Blueprint ? CompilerContext.Blueprint->ParentClass : nullptr;
		if (!Context || !Context->IsChildOf(UPrimitiveComponent::StaticClass()))
		{
			CompilerContext.MessageLog.Error(*LOCTEXT("NoTarget", "@@ needs a mesh connected to Target.").ToString(), this);
			BreakAllNodeLinks();
			return;
		}
	}

	// Side by side, every float in the range is ours: the engine call does it alone. Otherwise the
	// floats in between have to be read back and kept, which only the plugin's function does.
	const uint64 Full = Count >= 64 ? ~uint64(0) : (uint64(1) << Count) - 1;
	const bool bContiguous = Mask == Full;

	UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	if (bContiguous)
	{
		Set->FunctionReference.SetExternalMember(bWriteDefaults
			? SetNamedPrimitiveDataMulti::DefaultFloatArrayFunction
			: SetNamedPrimitiveDataMulti::FloatArrayFunction, UPrimitiveComponent::StaticClass());
	}
	else
	{
		Set->SetFromFunction(UPrimitiveDataSetLibrary::StaticClass()->FindFunctionByName(bWriteDefaults
			? GET_FUNCTION_NAME_CHECKED(UPrimitiveDataSetLibrary, SetDefaultCustomPrimitiveDataMasked)
			: GET_FUNCTION_NAME_CHECKED(UPrimitiveDataSetLibrary, SetCustomPrimitiveDataMasked)));
	}
	Set->AllocateDefaultPins();
	UEdGraphPin* ValuesInput = Set->FindPin(TEXT("Values"));
	UEdGraphPin* IndexInput = Set->FindPin(TEXT("DataIndex"));
	if (!Set->GetTargetFunction() || !ValuesInput || !IndexInput)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("MissingFunction",
			"@@: internal error - the primitive data function to call was not found.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Set->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Set->GetThenPin());
	// The slot is a literal, decided now, as on the single node.
	Schema->TrySetDefaultValue(*IndexInput, FString::FromInt(First));

	bool bWired = true;

	if (bContiguous)
	{
		// A member call: its self pin takes several wires or an array and loops, as the engine's own do.
		CompilerContext.MovePinLinksToIntermediate(*Target, *Set->FindPinChecked(UEdGraphSchema_K2::PN_Self));
	}
	else
	{
		Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("Mask")), FString::Printf(TEXT("%lld"), static_cast<int64>(Mask)));

		// A static function takes its meshes as an array: pass an array straight through, gather
		// separate wires (or self, unwired) into one. The loop happens in C++ rather than in script.
		UEdGraphPin* TargetsInput = Set->FindPinChecked(TEXT("Targets"));
		if (Target->LinkedTo.Num() == 1 && Target->LinkedTo[0]->PinType.IsArray())
		{
			CompilerContext.MovePinLinksToIntermediate(*Target, *TargetsInput);
		}
		else
		{
			TArray<UEdGraphPin*> Sources = Target->LinkedTo;
			if (Sources.ContainsByPredicate([](const UEdGraphPin* Source) { return Source->PinType.IsArray(); }))
			{
				CompilerContext.MessageLog.Error(*LOCTEXT("MixedTargets",
					"@@: Target takes one array, or any number of single meshes, but not both.").ToString(), this);
				BreakAllNodeLinks();
				return;
			}
			if (Sources.Num() == 0)
			{
				UK2Node_Self* Self = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
				Self->AllocateDefaultPins();
				Sources.Add(Self->FindPinChecked(UEdGraphSchema_K2::PN_Self));
			}
			Target->BreakAllPinLinks();

			UK2Node_MakeArray* Meshes = CompilerContext.SpawnIntermediateNode<UK2Node_MakeArray>(this, SourceGraph);
			Meshes->AllocateDefaultPins();
			bWired &= Schema->TryCreateConnection(Meshes->GetOutputPin(), TargetsInput);
			Meshes->PinConnectionListChanged(Meshes->GetOutputPin());
			for (int32 Index = 0; Index < Sources.Num(); ++Index)
			{
				if (Index > 0)
				{
					Meshes->AddInputPin();
				}
				bWired &= Schema->TryCreateConnection(Sources[Index], Meshes->FindPinChecked(Meshes->GetPinName(Index)));
			}
		}
	}

	// Every float in the range, in order. Gaps between parameters are left at zero: the masked function
	// never writes them.
	UK2Node_MakeArray* Values = CompilerContext.SpawnIntermediateNode<UK2Node_MakeArray>(this, SourceGraph);
	Values->AllocateDefaultPins();
	bWired &= Schema->TryCreateConnection(Values->GetOutputPin(), ValuesInput);
	Values->PinConnectionListChanged(Values->GetOutputPin());
	for (int32 Index = 1; Index < Count; ++Index)
	{
		Values->AddInputPin();
	}
	auto Element = [Values](int32 Index) { return Values->FindPinChecked(Values->GetPinName(Index)); };

	for (const FWrite& Write : Writes)
	{
		const int32 Offset = Write.Entry->Slot - First;
		if (Write.Entry->GetWidth() == 1)
		{
			// Moves the default too, when nothing is connected.
			bWired &= CompilerContext.MovePinLinksToIntermediate(*Write.Pin, *Element(Offset)).CanSafeConnect();
			continue;
		}

		// FLinearColor -> four floats, with an engine function so the cooked graph needs nothing else.
		UK2Node_CallFunction* Break = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Break->FunctionReference.SetExternalMember(GET_FUNCTION_NAME_CHECKED(UKismetMathLibrary, BreakColor), UKismetMathLibrary::StaticClass());
		Break->AllocateDefaultPins();
		bWired &= CompilerContext.MovePinLinksToIntermediate(*Write.Pin, *Break->FindPinChecked(TEXT("InColor"))).CanSafeConnect();
		const TCHAR* Channels[] = { TEXT("R"), TEXT("G"), TEXT("B"), TEXT("A") };
		for (int32 Channel = 0; Channel < 4; ++Channel)
		{
			bWired &= Schema->TryCreateConnection(Break->FindPinChecked(Channels[Channel]), Element(Offset + Channel));
		}
	}

	if (!bWired)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error wiring the primitive data write.").ToString(), this);
	}
	BreakAllNodeLinks();
}

