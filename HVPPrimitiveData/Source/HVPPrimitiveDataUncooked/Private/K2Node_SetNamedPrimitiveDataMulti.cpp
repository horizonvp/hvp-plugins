// Selection
// ---------------------------------------------------------------------------

bool UK2Node_SetNamedPrimitiveDataMulti::IsParameterSelected(const FGuid& Id) const
{
	return Selection.ContainsByPredicate([&Id](const FNamedPrimitiveDataSelection& Selected) { return Selected.Id == Id; });
}

void UK2Node_SetNamedPrimitiveDataMulti::SetParameterSelected(const FGuid& Id, bool bSelected)
{
	if (IsParameterSelected(Id) == bSelected)
	{
		return;
	}

	Modify();
	if (bSelected)
	{
		Selection.AddDefaulted_GetRef().Id = Id;
	}
	else
	{
		Selection.RemoveAll([&Id](const FNamedPrimitiveDataSelection& Selected) { return Selected.Id == Id; });
		DropValuePin(Id);
	}
	RefreshSelection(nullptr);
	Rebuild();
}

void UK2Node_SetNamedPrimitiveDataMulti::DropValuePin(const FGuid& Id)
{
	// Removed outright: left to reconstruction, a pin with a wire or a set value would be kept as an
	// orphan with a warning, which is right for a parameter that vanished but not for one unticked.
	if (UEdGraphPin* Pin = FindValuePin(Id))
	{
		Pin->BreakAllPinLinks();
		RemovePin(Pin);
	}
}

void UK2Node_SetNamedPrimitiveDataMulti::RefreshSelection(const TArray<UEdGraphPin*>* InPins)
{
	const UPrimitiveDataLegend* Legend = GetLegend(InPins);
	if (!Legend)
	{
		// Nothing to check against. Keep the selection as it is, so choosing the legend again restores it.
		return;
	}

	for (FNamedPrimitiveDataSelection& Selected : Selection)
	{
		// A selection the legend no longer has keeps its id and name, so an undo in the legend editor
		// brings it straight back. Only the kind drops, so it cannot compile against a missing type.
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry)
		{
			Selected.Id = Entry->Id;
			Selected.Name = Entry->Name;
		}
		Selected.Kind = SetNamedPrimitiveDataMulti::KindOf(Entry);
	}

	// Pins in the legend's order, whatever order they were ticked in. Missing ones go last.
	auto IndexOf = [Legend](const FNamedPrimitiveDataSelection& Selected)
	{
		const int32 Index = Legend->Parameters.IndexOfByPredicate(
			[&Selected](const FPrimitiveDataLegendEntry& Entry) { return Entry.Id == Selected.Id; });
		return Index == INDEX_NONE ? MAX_int32 : Index;
	};
	Selection.StableSort([&IndexOf](const FNamedPrimitiveDataSelection& A, const FNamedPrimitiveDataSelection& B)
	{
		return IndexOf(A) < IndexOf(B);
	});
}

void UK2Node_SetNamedPrimitiveDataMulti::Rebuild()
{
	ReconstructNode();
	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
	if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_SetNamedPrimitiveDataMulti::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin || Pin->PinName != LegendPinName)
	{
		return;
	}

	// A new legend: keep every ticked parameter it also has (by id, or by name for a legend that shares
	// the layout), drop the rest.
	Modify();
	const UPrimitiveDataLegend* Legend = GetLegend();
	Selection.RemoveAll([this, Legend](const FNamedPrimitiveDataSelection& Selected)
	{
		if (Resolve(Legend, Selected))
		{
			return false;
		}
		DropValuePin(Selected.Id);
		return true;
	});
	RefreshSelection(nullptr);
	Rebuild();
	OnParametersOffered.Broadcast();
}

void UK2Node_SetNamedPrimitiveDataMulti::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// The new pins only get their defaults copied over after this returns: read the legend off the old ones.
	if (UPrimitiveDataLegend* Legend = GetLegend(&OldPins))
	{
		PreloadObject(Legend);
	}
	RefreshSelection(&OldPins);

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

UK2Node::ERedirectType UK2Node_SetNamedPrimitiveDataMulti::DoPinsMatchForReconstruction(const UEdGraphPin* NewPin,
	int32 NewPinIndex, const UEdGraphPin* OldPin, int32 OldPinIndex) const
{
	if (NewPin && OldPin && NewPin->Direction == OldPin->Direction && NewPin->PinName == OldPin->PinName)
	{
		// A parameter whose type changed in the legend: its wire and value no longer fit, so let them go
		// rather than carry a colour into a float.
		const bool bSameType = NewPin->PinType.PinCategory == OldPin->PinType.PinCategory
			&& NewPin->PinType.PinSubCategoryObject == OldPin->PinType.PinSubCategoryObject;
		if (!bSameType)
		{
			return ERedirectType_None;
		}
	}
	return Super::DoPinsMatchForReconstruction(NewPin, NewPinIndex, OldPin, OldPinIndex);
}

void UK2Node_SetNamedPrimitiveDataMulti::PreloadRequiredAssets()
{
	if (UPrimitiveDataLegend* Legend = GetLegend())
	{
		PreloadObject(Legend);
	}
	Super::PreloadRequiredAssets();
}

bool UK2Node_SetNamedPrimitiveDataMulti::GetWriteRange(int32& OutFirst, int32& OutCount, uint64& OutMask) const
{
	OutFirst = 0;
	OutCount = 0;
	OutMask = 0;

	const UPrimitiveDataLegend* Legend = GetLegend();
	int32 First = MAX_int32;
	int32 End = 0;
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry && Entry->HasSlot())
		{
			First = FMath::Min(First, Entry->Slot);
			End = FMath::Max(End, Entry->Slot + Entry->GetWidth());
		}
	}
	if (First == MAX_int32)
	{
		return false;
	}

	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry && Entry->HasSlot())
		{
			for (int32 Float = 0; Float < Entry->GetWidth(); ++Float)
			{
				OutMask |= uint64(1) << (Entry->Slot - First + Float);
			}
		}
	}
	OutFirst = First;
	OutCount = End - First;
	return true;
}

