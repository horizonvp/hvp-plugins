void UK2Node_SetWebState::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);
	if (!CheckWebSource(CompilerContext))
	{
		BreakAllNodeLinks();
		return;
	}

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Call->FunctionReference.SetExternalMember(GetTargetFunctionName(), UCodeAnimationWeb::StaticClass());
	Call->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Call->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Call->GetThenPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(WebPinName), *Call->FindPinChecked(UEdGraphSchema_K2::PN_Self));
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(InstantPinName), *Call->FindPinChecked(TEXT("bInstant")));
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(SuccessPinName), *Call->GetReturnValuePin());

	UEdGraphPin* State = FindPinChecked(StatePinName);
	UEdGraphPin* NewState = Call->FindPinChecked(TEXT("NewState"));
	if (State->LinkedTo.Num() > 0)
	{
		CompilerContext.MovePinLinksToIntermediate(*State, *NewState);
	}
	else
	{
		// The literal is an enumerator name; SetState wants its value.
		int64 Value = StateEnum ? StateEnum->GetValueByNameString(State->DefaultValue) : FCString::Atoi64(*State->DefaultValue);
		if (Value == INDEX_NONE)
		{
			CompilerContext.MessageLog.Error(*FText::Format(LOCTEXT("BadState", "@@: '{0}' is not one of the Web's states."),
				FText::FromString(State->DefaultValue)).ToString(), this);
			Value = 0;
		}
		Schema->TrySetDefaultValue(*NewState, FString::FromInt(static_cast<int32>(Value)));
	}

	BreakAllNodeLinks();
}

FName UK2Node_SetWebState::GetTargetFunctionName() const
{
	return GET_FUNCTION_NAME_CHECKED(UCodeAnimationWeb, SetState);
}

