const FName UK2Node_SetNamedInstanceDataMulti::TargetPinName(UEdGraphSchema_K2::PN_Self);
const FName UK2Node_SetNamedInstanceDataMulti::InstanceIndexPinName(TEXT("InstanceIndex"));
const FName UK2Node_SetNamedInstanceDataMulti::LegendPinName(TEXT("Legend"));
const FName UK2Node_SetNamedInstanceDataMulti::MarkRenderStateDirtyPinName(TEXT("bMarkRenderStateDirty"));

namespace SetNamedInstanceDataMulti
{
	const TCHAR* DefaultColor = TEXT("(R=1.000000,G=1.000000,B=1.000000,A=1.000000)");
	const TCHAR* DefaultScalar = TEXT("0.0");

	ENamedPrimitiveDataValueKind KindOf(const FInstanceDataLegendEntry* Entry)
	{
		if (!Entry)
		{
			return ENamedPrimitiveDataValueKind::None;
		}
		return Entry->Type == EInstanceDataParameterType::Vector
			? ENamedPrimitiveDataValueKind::Vector
			: ENamedPrimitiveDataValueKind::Scalar;
	}
}

