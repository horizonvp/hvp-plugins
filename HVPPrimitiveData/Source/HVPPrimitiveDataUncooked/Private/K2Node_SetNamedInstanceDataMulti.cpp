void UK2Node_SetNamedInstanceDataMulti::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UInstanceDataLegend* Legend = GetLegend();
	if (!Legend)
	{
		MessageLog.Error(*LOCTEXT("NoLegend", "@@ has no Instance Data Legend chosen.").ToString(), this);
		return;
	}
	if (Selection.Num() == 0)
	{
		MessageLog.Error(*LOCTEXT("NothingTicked", "@@ sets nothing - tick its parameters in the Details panel.").ToString(), this);
		return;
	}
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (!Entry)
		{
			MessageLog.Error(*FText::Format(LOCTEXT("NoParameter", "@@: parameter '{0}' is not in {1}."),
				FText::FromName(Selected.Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (!Entry->HasSlot())
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("NoSlot", "@@: '{0}' has no slot in {1} - the legend is out of room. Open it for details."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (SetNamedInstanceDataMulti::KindOf(Entry) != Selected.Kind)
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("StaleKind", "@@: '{0}' changed type in {1}. Refresh the node (right-click > Refresh Nodes)."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
	}
}

void UK2Node_SetNamedInstanceDataMulti::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	const UInstanceDataLegend* Legend = GetLegend();

	// Validation says why for each of these; all that is left is to emit nothing.
	TArray<NamedDataNodeExpansion::FValueWrite> Writes;
	bool bValid = Legend != nullptr && Selection.Num() > 0;
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		UEdGraphPin* Pin = FindValuePin(Selected.Id);
		if (!Entry || !Entry->HasSlot() || !Pin || SetNamedInstanceDataMulti::KindOf(Entry) != Selected.Kind)
		{
			bValid = false;
			break;
		}
		Writes.Add({ Pin, Entry->Slot, Entry->GetWidth() });
	}
	int32 First = 0;
	int32 Count = 0;
	uint64 Mask = 0;
	if (!bValid || !GetWriteRange(First, Count, Mask))
	{
		BreakAllNodeLinks();
		return;
	}
	for (NamedDataNodeExpansion::FValueWrite& Write : Writes)
	{
		Write.Offset -= First;
	}

	UEdGraphPin* Target = FindPinChecked(TargetPinName);
	if (!NamedDataNodeExpansion::CheckSelfTarget(CompilerContext, this, Target, UInstancedStaticMeshComponent::StaticClass(),
		LOCTEXT("NoTarget", "@@ needs an instanced static mesh connected to Target.")))
	{
		BreakAllNodeLinks();
		return;
	}

	UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Set->SetFromFunction(UInstanceDataSetLibrary::StaticClass()->FindFunctionByName(
		GET_FUNCTION_NAME_CHECKED(UInstanceDataSetLibrary, SetInstanceCustomDataMasked)));
	Set->AllocateDefaultPins();
	if (!Set->GetTargetFunction())
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("MissingFunction",
			"@@: internal error - the instance data function to call was not found.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Set->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Set->GetThenPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(InstanceIndexPinName), *Set->FindPinChecked(TEXT("InstanceIndex")));
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(MarkRenderStateDirtyPinName), *Set->FindPinChecked(TEXT("bMarkRenderStateDirty")));

	// The slot and the mask are literals, decided now.
	Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("DataIndex")), FString::FromInt(First));
	Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("Mask")), FString::Printf(TEXT("%lld"), static_cast<int64>(Mask)));

	bool bWired = true;
	if (!NamedDataNodeExpansion::GatherTargets(CompilerContext, this, SourceGraph, Target, Set->FindPinChecked(TEXT("Targets")), bWired))
	{
		BreakAllNodeLinks();
		return;
	}
	bWired &= NamedDataNodeExpansion::WireValues(CompilerContext, this, SourceGraph, Set->FindPinChecked(TEXT("Values")), Count, Writes);

	if (!bWired)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error wiring the instance data write.").ToString(), this);
	}
	BreakAllNodeLinks();
}

