FName UK2Node_SetNamedPrimitiveDataMulti::PinNameFor(const FGuid& Id)
{
	return FName(*FString::Printf(TEXT("Param_%s"), *Id.ToString(EGuidFormats::Digits)));
}

void UK2Node_SetNamedPrimitiveDataMulti::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* Target = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UPrimitiveComponent::StaticClass(), TargetPinName);
	Target->PinFriendlyName = LOCTEXT("TargetName", "Target");
	Target->PinToolTip = LOCTEXT("TargetTooltip",
		"The mesh (any primitive component) to set the data on. Wire in several, or an array, to set it on each.").ToString();

	UEdGraphPin* Legend = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UPrimitiveDataLegend::StaticClass(), LegendPinName);
	Legend->bNotConnectable = true;
	Legend->PinToolTip = LOCTEXT("LegendTooltip",
		"The Primitive Data Legend that names the parameters. Tick the ones to set in the Details panel.").ToString();

	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		CreateValuePin(Selected);
	}

	Super::AllocateDefaultPins();
}

void UK2Node_SetNamedPrimitiveDataMulti::CreateValuePin(const FNamedPrimitiveDataSelection& Selected)
{
	UEdGraphPin* Value = nullptr;
	switch (Selected.Kind)
	{
	case ENamedPrimitiveDataValueKind::Scalar:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PinNameFor(Selected.Id));
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetNamedPrimitiveDataMulti::DefaultScalar);
		break;
	case ENamedPrimitiveDataValueKind::Vector:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, TBaseStructure<FLinearColor>::Get(), PinNameFor(Selected.Id));
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetNamedPrimitiveDataMulti::DefaultColor);
		break;
	default:
		// No longer in the legend: no pin, and validation says why.
		return;
	}
	Value->PinFriendlyName = FText::FromName(Selected.Name);
}

void UK2Node_SetNamedPrimitiveDataMulti::PostReconstructNode()
{
	Super::PostReconstructNode();

	// Here rather than as the pins are made: during reconstruction the Legend pin has no value yet.
	const UPrimitiveDataLegend* Legend = GetLegend();
	for (const FNamedPrimitiveDataSelection& Selected : Selection)
	{
		UEdGraphPin* Value = FindValuePin(Selected.Id);
		const FPrimitiveDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Value && Entry && Entry->HasSlot())
		{
			Value->PinToolTip = Entry->GetWidth() > 1
				? FString::Printf(TEXT("%s (slots %d-%d)"), *Selected.Name.ToString(), Entry->Slot, Entry->Slot + Entry->GetWidth() - 1)
				: FString::Printf(TEXT("%s (slot %d)"), *Selected.Name.ToString(), Entry->Slot);
		}
	}
}

UEdGraphPin* UK2Node_SetNamedPrimitiveDataMulti::FindPinIn(FName Name, const TArray<UEdGraphPin*>* InPins) const
{
	const TArray<UEdGraphPin*>& Search = InPins ? *InPins : Pins;
	for (UEdGraphPin* Pin : Search)
	{
		if (Pin && Pin->PinName == Name)
		{
			return Pin;
		}
	}
	return nullptr;
}

UEdGraphPin* UK2Node_SetNamedPrimitiveDataMulti::FindValuePin(const FGuid& Id) const
{
	return FindPinIn(PinNameFor(Id), nullptr);
}

UPrimitiveDataLegend* UK2Node_SetNamedPrimitiveDataMulti::GetLegend(const TArray<UEdGraphPin*>* InPins) const
{
	const UEdGraphPin* Pin = FindPinIn(LegendPinName, InPins);
	return Pin ? Cast<UPrimitiveDataLegend>(Pin->DefaultObject) : nullptr;
}

const FPrimitiveDataLegendEntry* UK2Node_SetNamedPrimitiveDataMulti::Resolve(const UPrimitiveDataLegend* Legend,
	const FNamedPrimitiveDataSelection& Selected) const
{
	if (!Legend)
	{
		return nullptr;
	}
	if (const FPrimitiveDataLegendEntry* ById = Legend->FindParameter(Selected.Id))
	{
		return ById;
	}
	return Selected.Name.IsNone() ? nullptr : Legend->FindParameter(Selected.Name);
}

