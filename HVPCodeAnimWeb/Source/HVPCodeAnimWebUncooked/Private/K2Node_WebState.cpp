void UK2Node_GetWebState::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);
	if (!CheckWebSource(CompilerContext))
	{
		BreakAllNodeLinks();
		return;
	}

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Call->FunctionReference.SetExternalMember(GET_FUNCTION_NAME_CHECKED(UCodeAnimationWeb, GetState), UCodeAnimationWeb::StaticClass());
	Call->AllocateDefaultPins();
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(WebPinName), *Call->FindPinChecked(UEdGraphSchema_K2::PN_Self));

	UEdGraphPin* Result = FindPinChecked(UEdGraphSchema_K2::PN_ReturnValue);
	if (StateEnum)
	{
		UK2Node_CastByteToEnum* ToEnum = CompilerContext.SpawnIntermediateNode<UK2Node_CastByteToEnum>(this, SourceGraph);
		ToEnum->Enum = StateEnum;
		ToEnum->bSafe = false;
		ToEnum->AllocateDefaultPins();
		if (!Schema->TryCreateConnection(Call->GetReturnValuePin(), ToEnum->FindPinChecked(TEXT("Byte"))))
		{
			CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error converting the state.").ToString(), this);
		}
		CompilerContext.MovePinLinksToIntermediate(*Result, *ToEnum->FindPinChecked(UEdGraphSchema_K2::PN_ReturnValue));
	}
	else
	{
		CompilerContext.MovePinLinksToIntermediate(*Result, *Call->GetReturnValuePin());
	}

	BreakAllNodeLinks();
}

