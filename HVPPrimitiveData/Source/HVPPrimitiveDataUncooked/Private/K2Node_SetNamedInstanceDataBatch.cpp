void UK2Node_SetNamedInstanceDataBatch::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UInstanceDataLegend* Legend = GetLegend();
	if (!Legend)
	{
		MessageLog.Error(*LOCTEXT("NoLegend", "@@ has no Instance Data Legend chosen.").ToString(), this);
		return;
	}
	if (Selection.Num() == 0)
	{
		MessageLog.Error(*LOCTEXT("NothingTicked", "@@ sets nothing - tick its parameters in the Details panel.").ToString(), this);
		return;
	}
	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (!Entry)
		{
			MessageLog.Error(*FText::Format(LOCTEXT("NoParameter", "@@: parameter '{0}' is not in {1}."),
				FText::FromName(Selected.Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (!Entry->HasSlot())
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("NoSlot", "@@: '{0}' has no slot in {1} - the legend is out of room. Open it for details."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (SetNamedInstanceDataBatch::KindOf(Entry) != Selected.Kind)
		{
			MessageLog.Error(*FText::Format(
				LOCTEXT("StaleKind", "@@: '{0}' changed type in {1}. Refresh the node (right-click > Refresh Nodes)."),
				FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		}
		else if (Selected.bPerInstance)
		{
			const UEdGraphPin* Pin = FindValuePin(Selected.Id);
			if (Pin && Pin->LinkedTo.Num() == 0)
			{
				MessageLog.Warning(*FText::Format(
					LOCTEXT("EmptyColumn", "@@: '{0}' is per instance but has no array connected, so it sets nothing."),
					FText::FromName(Selected.Name)).ToString(), this);
			}
		}
	}
}

void UK2Node_SetNamedInstanceDataBatch::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	const UInstanceDataLegend* Legend = GetLegend();

	struct FWrite
	{
		const FInstanceDataLegendEntry* Entry;
		UEdGraphPin* Pin;
		bool bPerInstance;
	};
	TArray<FWrite> Writes;
	bool bValid = Legend != nullptr && Selection.Num() > 0;
	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		UEdGraphPin* Pin = FindValuePin(Selected.Id);
		if (!Entry || !Entry->HasSlot() || !Pin || SetNamedInstanceDataBatch::KindOf(Entry) != Selected.Kind)
		{
			bValid = false;
			break;
		}
		Writes.Add({ Entry, Pin, Selected.bPerInstance });
	}
	int32 First = 0;
	int32 Count = 0;
	uint64 AllMask = 0;
	if (!bValid || !GetWriteRange(First, Count, AllMask))
	{
		BreakAllNodeLinks();
		return;
	}

	UEdGraphPin* Target = FindPinChecked(TargetPinName);
	if (!NamedDataNodeExpansion::CheckSelfTarget(CompilerContext, this, Target, UInstancedStaticMeshComponent::StaticClass(),
		LOCTEXT("NoTarget", "@@ needs an instanced static mesh connected to Target.")))
	{
		BreakAllNodeLinks();
		return;
	}

	UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Set->SetFromFunction(UInstanceDataSetLibrary::StaticClass()->FindFunctionByName(
		GET_FUNCTION_NAME_CHECKED(UInstanceDataSetLibrary, SetInstanceCustomDataBatch)));
	Set->AllocateDefaultPins();
	if (!Set->GetTargetFunction())
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("MissingFunction",
			"@@: internal error - the instance data function to call was not found.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Set->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Set->GetThenPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(InstanceIndicesPinName), *Set->FindPinChecked(TEXT("InstanceIndices")));
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(MarkRenderStateDirtyPinName), *Set->FindPinChecked(TEXT("bMarkRenderStateDirty")));
	Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("DataIndex")), FString::FromInt(First));

	bool bWired = true;
	if (!NamedDataNodeExpansion::GatherTargets(CompilerContext, this, SourceGraph, Target, Set->FindPinChecked(TEXT("Targets")), bWired))
	{
		BreakAllNodeLinks();
		return;
	}

	// One value for every instance: into the Uniform floats, owned by the mask, as on the multiple node.
	uint64 UniformMask = 0;
	TArray<NamedDataNodeExpansion::FValueWrite> Uniform;
	for (const FWrite& Write : Writes)
	{
		if (!Write.bPerInstance)
		{
			const int32 Offset = Write.Entry->Slot - First;
			Uniform.Add({ Write.Pin, Offset, Write.Entry->GetWidth() });
			for (int32 Float = 0; Float < Write.Entry->GetWidth(); ++Float)
			{
				UniformMask |= uint64(1) << (Offset + Float);
			}
		}
	}
	Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("Mask")), FString::Printf(TEXT("%lld"), static_cast<int64>(UniformMask)));
	if (Uniform.Num() > 0)
	{
		bWired &= NamedDataNodeExpansion::WireValues(CompilerContext, this, SourceGraph, Set->FindPinChecked(TEXT("Uniform")), Count, Uniform);
	}

	// A value per instance: one column each, made as a struct, gathered into the Columns array.
	UK2Node_MakeArray* Columns = nullptr;
	int32 ColumnCount = 0;
	for (const FWrite& Write : Writes)
	{
		if (!Write.bPerInstance)
		{
			continue;
		}
		if (!Columns)
		{
			Columns = CompilerContext.SpawnIntermediateNode<UK2Node_MakeArray>(this, SourceGraph);
			Columns->AllocateDefaultPins();
			bWired &= Schema->TryCreateConnection(Columns->GetOutputPin(), Set->FindPinChecked(TEXT("Columns")));
			Columns->PinConnectionListChanged(Columns->GetOutputPin());
		}
		else
		{
			Columns->AddInputPin();
		}

		UK2Node_MakeStruct* Column = CompilerContext.SpawnIntermediateNode<UK2Node_MakeStruct>(this, SourceGraph);
		Column->StructType = FInstanceDataColumn::StaticStruct();
		Column->bMadeAfterOverridePinRemoval = true;
		Column->AllocateDefaultPins();
		Schema->TrySetDefaultValue(*Column->FindPinChecked(GET_MEMBER_NAME_CHECKED(FInstanceDataColumn, Offset)),
			FString::FromInt(Write.Entry->Slot - First));
		Schema->TrySetDefaultValue(*Column->FindPinChecked(GET_MEMBER_NAME_CHECKED(FInstanceDataColumn, Width)),
			FString::FromInt(Write.Entry->GetWidth()));
		const FName ValuesMember = Write.Entry->GetWidth() == 1
			? GET_MEMBER_NAME_CHECKED(FInstanceDataColumn, Scalars)
			: GET_MEMBER_NAME_CHECKED(FInstanceDataColumn, Colors);
		bWired &= CompilerContext.MovePinLinksToIntermediate(*Write.Pin, *Column->FindPinChecked(ValuesMember)).CanSafeConnect();

		UEdGraphPin* ColumnOut = nullptr;
		for (UEdGraphPin* Pin : Column->Pins)
		{
			if (Pin->Direction == EGPD_Output)
			{
				ColumnOut = Pin;
				break;
			}
		}
		bWired &= ColumnOut && Schema->TryCreateConnection(ColumnOut, Columns->FindPinChecked(Columns->GetPinName(ColumnCount)));
		++ColumnCount;
	}

	if (!bWired)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error wiring the instance data write.").ToString(), this);
	}
	BreakAllNodeLinks();
}

