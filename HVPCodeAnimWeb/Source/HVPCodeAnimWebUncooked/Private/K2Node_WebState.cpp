const FName UK2Node_SetWebState::StatePinName(TEXT("State"));
const FName UK2Node_SetWebState::InstantPinName(TEXT("Instant"));
const FName UK2Node_SetWebState::SuccessPinName(TEXT("Success"));

UEnum* CodeAnimWebNodes::GetStateEnum(const UClass* WebClass)
{
	const UCodeAnimationWeb* Defaults = WebClass ? Cast<UCodeAnimationWeb>(WebClass->GetDefaultObject()) : nullptr;
	return Defaults ? Defaults->StateEnum.Get() : nullptr;
}

namespace WebStateNodes
{
	/** Retypes a byte pin to an enum, resetting what no longer fits. */
	static void Retype(UEdGraphPin* Pin, UEnum* Enum, bool bSetDefault)
	{
		if (!Pin || Pin->PinType.PinSubCategoryObject == Enum)
		{
			return;
		}
		Pin->Modify();
		Pin->BreakAllPinLinks();
		Pin->PinType.PinSubCategoryObject = Enum;
		if (bSetDefault)
		{
			const FString Default = Enum && Enum->NumEnums() > 1 ? Enum->GetNameStringByIndex(0) : TEXT("0");
			GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Pin, Default);
		}
	}
}

