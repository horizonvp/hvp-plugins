void UK2Node_SetNamedInstanceData::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UInstanceDataLegend* Legend = GetLegend();
	if (!Legend)
	{
		MessageLog.Error(*LOCTEXT("NoLegend", "@@ has no Instance Data Legend chosen.").ToString(), this);
		return;
	}

	const FInstanceDataLegendEntry* Entry = ResolveParameter();
	if (!Entry)
	{
		MessageLog.Error(*FText::Format(LOCTEXT("NoParameter", "@@: parameter '{0}' is not in {1}."),
			FText::FromName(ParameterName), FText::FromString(Legend->GetName())).ToString(), this);
		return;
	}
	if (!Entry->HasSlot())
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("NoSlot", "@@: '{0}' has no slot in {1} - the legend is out of room. Open it for details."),
			FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
		return;
	}
	if (KindOf(Entry) != ValueKind)
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("StaleKind", "@@: '{0}' changed type in {1}. Refresh the node (right-click > Refresh Nodes)."),
			FText::FromName(Entry->Name), FText::FromString(Legend->GetName())).ToString(), this);
	}
}

void UK2Node_SetNamedInstanceData::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	const FInstanceDataLegendEntry* Entry = ResolveParameter();
	UEdGraphPin* Value = FindPin(ValuePinName);

	// ValidateNodeDuringCompilation has already said why.
	if (!Entry || !Entry->HasSlot() || !Value || KindOf(Entry) != ValueKind)
	{
		BreakAllNodeLinks();
		return;
	}

	UEdGraphPin* Target = FindPinChecked(TargetPinName);
	if (!NamedDataNodeExpansion::CheckSelfTarget(CompilerContext, this, Target, UInstancedStaticMeshComponent::StaticClass(),
		LOCTEXT("NoTarget", "@@ needs an instanced static mesh connected to Target.")))
	{
		BreakAllNodeLinks();
		return;
	}

	UEdGraphPin* Instance = FindPinChecked(InstanceIndexPinName);
	UEdGraphPin* Dirty = FindPinChecked(MarkRenderStateDirtyPinName);
	const int32 Width = Entry->GetWidth();
	bool bWired = true;

	// Several meshes, or an array: SetCustomDataValue returns a bool, and the compiler only loops a call
	// over several targets when it has no outputs. So these go through the plugin's own function, which
	// takes the meshes as an array and loops in C++ - the multiple node's, with every float owned.
	const bool bManyTargets = Target->LinkedTo.Num() > 1
		|| (Target->LinkedTo.Num() == 1 && Target->LinkedTo[0]->PinType.IsArray());
	if (bManyTargets)
	{
		UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Set->SetFromFunction(UInstanceDataSetLibrary::StaticClass()->FindFunctionByName(
			GET_FUNCTION_NAME_CHECKED(UInstanceDataSetLibrary, SetInstanceCustomDataMasked)));
		Set->AllocateDefaultPins();

		CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Set->GetExecPin());
		CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Set->GetThenPin());
		CompilerContext.MovePinLinksToIntermediate(*Instance, *Set->FindPinChecked(TEXT("InstanceIndex")));
		CompilerContext.MovePinLinksToIntermediate(*Dirty, *Set->FindPinChecked(TEXT("bMarkRenderStateDirty")));
		Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("DataIndex")), FString::FromInt(Entry->Slot));
		Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("Mask")), FString::FromInt((1 << Width) - 1));

		if (!NamedDataNodeExpansion::GatherTargets(CompilerContext, this, SourceGraph, Target, Set->FindPinChecked(TEXT("Targets")), bWired))
		{
			BreakAllNodeLinks();
			return;
		}
		const NamedDataNodeExpansion::FValueWrite Write{ Value, 0, Width };
		bWired &= NamedDataNodeExpansion::WireValues(CompilerContext, this, SourceGraph, Set->FindPinChecked(TEXT("Values")), Width,
			MakeArrayView(&Write, 1));
		if (!bWired)
		{
			CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error wiring the instance data write.").ToString(), this);
		}
		BreakAllNodeLinks();
		return;
	}

	// One engine call per float: a scalar is one, a vector's red, green and blue are three in a row. Each
	// gets the node's Target, instance and dirty flag; the first takes them over, the rest copy them.
	TArray<UK2Node_CallFunction*> Sets;
	for (int32 Float = 0; Float < Width; ++Float)
	{
		UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Set->FunctionReference.SetExternalMember(
			GET_FUNCTION_NAME_CHECKED(UInstancedStaticMeshComponent, SetCustomDataValue), UInstancedStaticMeshComponent::StaticClass());
		Set->AllocateDefaultPins();
		// THE point of the node: the slot is a literal, decided now.
		Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("CustomDataIndex")), FString::FromInt(Entry->Slot + Float));
		Sets.Add(Set);
	}

	for (int32 Float = 0; Float < Sets.Num(); ++Float)
	{
		UK2Node_CallFunction* Set = Sets[Float];
		const bool bLast = Float == Sets.Num() - 1;
		auto Share = [&CompilerContext, bLast](UEdGraphPin* From, UEdGraphPin* To)
		{
			// The last one moves, so the earlier copies still have links to copy from.
			return (bLast ? CompilerContext.MovePinLinksToIntermediate(*From, *To) : CompilerContext.CopyPinLinksToIntermediate(*From, *To))
				.CanSafeConnect();
		};
		bWired &= Share(Target, Set->FindPinChecked(UEdGraphSchema_K2::PN_Self));
		bWired &= Share(Instance, Set->FindPinChecked(TEXT("InstanceIndex")));
		bWired &= Share(Dirty, Set->FindPinChecked(TEXT("bMarkRenderStateDirty")));
		if (Float > 0)
		{
			bWired &= Schema->TryCreateConnection(Sets[Float - 1]->GetThenPin(), Set->GetExecPin());
		}
	}

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Sets[0]->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Sets.Last()->GetThenPin());

	if (Width == 1)
	{
		bWired &= CompilerContext.MovePinLinksToIntermediate(*Value, *Sets[0]->FindPinChecked(TEXT("CustomDataValue"))).CanSafeConnect();
	}
	else
	{
		// One BreakColor feeds all three: an engine function, so the cooked graph needs nothing else.
		UK2Node_CallFunction* Break = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Break->FunctionReference.SetExternalMember(GET_FUNCTION_NAME_CHECKED(UKismetMathLibrary, BreakColor), UKismetMathLibrary::StaticClass());
		Break->AllocateDefaultPins();
		bWired &= CompilerContext.MovePinLinksToIntermediate(*Value, *Break->FindPinChecked(TEXT("InColor"))).CanSafeConnect();
		const TCHAR* Channels[] = { TEXT("R"), TEXT("G"), TEXT("B") };
		for (int32 Channel = 0; Channel < Sets.Num(); ++Channel)
		{
			bWired &= Schema->TryCreateConnection(Break->FindPinChecked(Channels[Channel]), Sets[Channel]->FindPinChecked(TEXT("CustomDataValue")));
		}
	}

	if (!bWired)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("WireFailed", "@@: internal error wiring the instance data write.").ToString(), this);
	}
	BreakAllNodeLinks();
}

