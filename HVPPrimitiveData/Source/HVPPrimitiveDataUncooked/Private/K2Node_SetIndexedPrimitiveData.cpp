void UK2Node_SetIndexedPrimitiveData::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UPrimitiveDataIndex* Index = GetIndex();
	if (!Index)
	{
		MessageLog.Error(*LOCTEXT("NoIndex", "@@ has no Primitive Data Index chosen.").ToString(), this);
		return;
	}

	const FPrimitiveDataIndexEntry* Entry = ResolveParameter();
	if (!Entry)
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("NoParameter", "@@: parameter '{0}' is not in {1}."),
			FText::FromName(ParameterName), FText::FromString(Index->GetName())).ToString(), this);
		return;
	}
	if (!Entry->HasSlot())
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("NoSlot", "@@: '{0}' has no slot in {1} - the index is out of room. Open it for details."),
			FText::FromName(Entry->Name), FText::FromString(Index->GetName())).ToString(), this);
		return;
	}
	if (KindOf(Entry) != ValueKind)
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("StaleKind", "@@: '{0}' changed type in {1}. Refresh the node (right-click > Refresh Nodes)."),
			FText::FromName(Entry->Name), FText::FromString(Index->GetName())).ToString(), this);
		return;
	}

	// NOT checked here: whether Target is connected. The compiler validates AFTER expansion, by which
	// point ExpandNode has handed every link to the intermediate call and this node has none - so a
	// link check here fails on every correctly wired node. It lives in ExpandNode, before the move.
}

void UK2Node_SetIndexedPrimitiveData::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	const FPrimitiveDataIndexEntry* Entry = ResolveParameter();
	UEdGraphPin* Value = FindPin(ValuePinName);

	// ValidateNodeDuringCompilation has already said why; all that is left is to not emit anything.
	if (!Entry || !Entry->HasSlot() || !Value || KindOf(Entry) != ValueKind)
	{
		BreakAllNodeLinks();
		return;
	}

	// Unwired Target means "self", as on any engine node - fine when this Blueprint IS a primitive
	// component, an error anywhere else. Checked here rather than left to the intermediate call so the
	// message names this node, not a node the user never placed.
	UEdGraphPin* Target = FindPinChecked(TargetPinName);
	if (Target->LinkedTo.Num() == 0)
	{
		const UClass* Context = CompilerContext.Blueprint ? CompilerContext.Blueprint->ParentClass : nullptr;
		if (!Context || !Context->IsChildOf(UPrimitiveComponent::StaticClass()))
		{
			CompilerContext.MessageLog.Error(*LOCTEXT("NoTarget", "@@ needs a mesh connected to Target.").ToString(), this);
			BreakAllNodeLinks();
			return;
		}
	}

	const bool bVector = (ValueKind == EIndexedPrimitiveDataValueKind::Vector);

	UK2Node_CallFunction* Set = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	Set->FunctionReference.SetExternalMember(bVector
		? GET_FUNCTION_NAME_CHECKED(UPrimitiveComponent, SetCustomPrimitiveDataVector4)
		: GET_FUNCTION_NAME_CHECKED(UPrimitiveComponent, SetCustomPrimitiveDataFloat),
		UPrimitiveComponent::StaticClass());
	Set->AllocateDefaultPins();

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *Set->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *Set->GetThenPin());
	CompilerContext.MovePinLinksToIntermediate(*Target, *Set->FindPinChecked(UEdGraphSchema_K2::PN_Self));

	// THE point of the node: the slot is a literal, decided now, never looked up at runtime.
	Schema->TrySetDefaultValue(*Set->FindPinChecked(TEXT("DataIndex")), FString::FromInt(Entry->Slot));

	if (!bVector)
	{
		CompilerContext.MovePinLinksToIntermediate(*Value, *Set->FindPinChecked(TEXT("Value")));
	}
	else
	{
		// FLinearColor -> FVector4. The engine has no single conversion for this, so it is BreakColor
		// into MakeVector4: both are engine functions, which keeps the cooked Blueprint free of any
		// dependency on this plugin.
		UK2Node_CallFunction* Break = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Break->FunctionReference.SetExternalMember(
			GET_FUNCTION_NAME_CHECKED(UKismetMathLibrary, BreakColor), UKismetMathLibrary::StaticClass());
		Break->AllocateDefaultPins();

		UK2Node_CallFunction* Make = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Make->FunctionReference.SetExternalMember(
			GET_FUNCTION_NAME_CHECKED(UKismetMathLibrary, MakeVector4), UKismetMathLibrary::StaticClass());
		Make->AllocateDefaultPins();

		// Moves the default colour too, when nothing is connected.
		CompilerContext.MovePinLinksToIntermediate(*Value, *Break->FindPinChecked(TEXT("InColor")));

		const TPair<const TCHAR*, const TCHAR*> Channels[] = {
			{ TEXT("R"), TEXT("X") }, { TEXT("G"), TEXT("Y") }, { TEXT("B"), TEXT("Z") }, { TEXT("A"), TEXT("W") } };
		bool bWired = true;
		for (const TPair<const TCHAR*, const TCHAR*>& Channel : Channels)
		{
			bWired &= Schema->TryCreateConnection(Break->FindPinChecked(Channel.Key), Make->FindPinChecked(Channel.Value));
		}
		bWired &= Schema->TryCreateConnection(Make->GetReturnValuePin(), Set->FindPinChecked(TEXT("Value")));

		if (!bWired)
		{
			CompilerContext.MessageLog.Error(
				*LOCTEXT("WireFailed", "@@: internal error converting the colour for SetCustomPrimitiveDataVector4.").ToString(), this);
		}
	}

	BreakAllNodeLinks();
}

