// A self pin for the same reason as on the single node: only a self pin takes several wires or an array.
const FName UK2Node_SetNamedPrimitiveDataMulti::TargetPinName(UEdGraphSchema_K2::PN_Self);
const FName UK2Node_SetNamedPrimitiveDataMulti::LegendPinName(TEXT("Legend"));

namespace SetNamedPrimitiveDataMulti
{
	const TCHAR* DefaultColor = TEXT("(R=1.000000,G=1.000000,B=1.000000,A=1.000000)");
	const TCHAR* DefaultScalar = TEXT("0.0");

	/**
	 * Not GET_FUNCTION_NAME_CHECKED: the engine overloads these names (TArray and TConstArrayView), so
	 * taking their address does not compile. ExpandNode checks the function is really there instead.
	 */
	const FName FloatArrayFunction(TEXT("SetCustomPrimitiveDataFloatArray"));
	const FName DefaultFloatArrayFunction(TEXT("SetDefaultCustomPrimitiveDataFloatArray"));

	int32 WidthOf(ENamedPrimitiveDataValueKind Kind)
	{
		return Kind == ENamedPrimitiveDataValueKind::Vector ? 4 : 1;
	}

	ENamedPrimitiveDataValueKind KindOf(const FPrimitiveDataLegendEntry* Entry)
	{
		if (!Entry)
		{
			return ENamedPrimitiveDataValueKind::None;
		}
		return Entry->Type == EPrimitiveDataParameterType::Vector
			? ENamedPrimitiveDataValueKind::Vector
			: ENamedPrimitiveDataValueKind::Scalar;
	}
}

