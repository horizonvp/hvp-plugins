// A SELF pin, not a plain object pin named Target: the schema only lets an array or several wires into
// a pin that is self, and only then on a node answering AllowMultipleSelfs. Shown as "Target", as the
// engine's own function nodes show theirs.
const FName UK2Node_SetIndexedPrimitiveData::TargetPinName(UEdGraphSchema_K2::PN_Self);
const FName UK2Node_SetIndexedPrimitiveData::IndexPinName(TEXT("Index"));
const FName UK2Node_SetIndexedPrimitiveData::ParameterPinName(TEXT("Parameter"));
const FName UK2Node_SetIndexedPrimitiveData::ValuePinName(TEXT("Value"));

namespace SetIndexedPrimitiveData
{
	/** White, opaque. A colour pin arriving as transparent black would read as "nothing happened". */
	const TCHAR* DefaultColor = TEXT("(R=1.000000,G=1.000000,B=1.000000,A=1.000000)");
	const TCHAR* DefaultScalar = TEXT("0.0");
}

// ---------------------------------------------------------------------------
// Pins
// ---------------------------------------------------------------------------

void UK2Node_SetIndexedPrimitiveData::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* Target = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UPrimitiveComponent::StaticClass(), TargetPinName);
	Target->PinFriendlyName = LOCTEXT("TargetName", "Target");
	Target->PinToolTip = LOCTEXT("TargetTooltip",
		"The mesh (any primitive component) to set the data on. Wire in several, or an array, to set it on each.").ToString();

	// Choices made on the node, not data - see the class comment. bNotConnectable leaves only the
	// default-value widget: the asset picker here, the parameter dropdown on the next pin.
	UEdGraphPin* Index = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UPrimitiveDataIndex::StaticClass(), IndexPinName);
	Index->bNotConnectable = true;
	Index->PinToolTip = LOCTEXT("IndexTooltip", "The Primitive Data Index that names the parameters.").ToString();

	UEdGraphPin* Parameter = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, ParameterPinName);
	Parameter->bNotConnectable = true;
	Parameter->PinToolTip = LOCTEXT("ParameterTooltip", "Which of the index's parameters to set.").ToString();

	CreateValuePin();

	Super::AllocateDefaultPins();
}

void UK2Node_SetIndexedPrimitiveData::CreateValuePin()
{
	UEdGraphPin* Value = nullptr;
	switch (ValueKind)
	{
	case EIndexedPrimitiveDataValueKind::Scalar:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, ValuePinName);
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetIndexedPrimitiveData::DefaultScalar);
		break;
	case EIndexedPrimitiveDataValueKind::Vector:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, TBaseStructure<FLinearColor>::Get(), ValuePinName);
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetIndexedPrimitiveData::DefaultColor);
		break;
	default:
		// No parameter chosen: no Value pin at all, rather than a wildcard that would accept anything
		// and then fail to compile.
		break;
	}
}

UEdGraphPin* UK2Node_SetIndexedPrimitiveData::FindPinIn(FName Name, const TArray<UEdGraphPin*>* InPins) const
{
	const TArray<UEdGraphPin*>& Search = InPins ? *InPins : Pins;
	for (UEdGraphPin* Pin : Search)
	{
		if (Pin && Pin->PinName == Name)
		{
			return Pin;
		}
	}
	return nullptr;
}

UPrimitiveDataIndex* UK2Node_SetIndexedPrimitiveData::GetIndex(const TArray<UEdGraphPin*>* InPins) const
{
	const UEdGraphPin* Pin = FindPinIn(IndexPinName, InPins);
	return Pin ? Cast<UPrimitiveDataIndex>(Pin->DefaultObject) : nullptr;
}

const FPrimitiveDataIndexEntry* UK2Node_SetIndexedPrimitiveData::ResolveParameter(const TArray<UEdGraphPin*>* InPins) const
{
	const UPrimitiveDataIndex* Index = GetIndex(InPins);
	if (!Index)
	{
		return nullptr;
	}
	if (const FPrimitiveDataIndexEntry* ById = Index->FindParameter(ParameterId))
	{
		return ById;
	}
	const UEdGraphPin* Pin = FindPinIn(ParameterPinName, InPins);
	return Pin ? Index->FindParameter(FName(*Pin->DefaultValue)) : nullptr;
}

EIndexedPrimitiveDataValueKind UK2Node_SetIndexedPrimitiveData::KindOf(const FPrimitiveDataIndexEntry* Entry)
{
	if (!Entry)
	{
		return EIndexedPrimitiveDataValueKind::None;
	}
	return Entry->Type == EPrimitiveDataParameterType::Vector
		? EIndexedPrimitiveDataValueKind::Vector
		: EIndexedPrimitiveDataValueKind::Scalar;
}

void UK2Node_SetIndexedPrimitiveData::RefreshSelection(const TArray<UEdGraphPin*>* InPins)
{
	const FPrimitiveDataIndexEntry* Entry = ResolveParameter(InPins);
	if (Entry)
	{
		ParameterId = Entry->Id;
		ParameterName = Entry->Name;
	}
	// A selection the index no longer has keeps its GUID: if the entry comes back (an undo in the
	// index editor) the node picks it straight up again. The kind still has to drop, so the node
	// cannot compile against a type that is no longer there.
	ValueKind = KindOf(Entry);
}

void UK2Node_SetIndexedPrimitiveData::SetValueKind(EIndexedPrimitiveDataValueKind NewKind)
{
	if (NewKind == ValueKind)
	{
		return;
	}

	Modify();
	if (UEdGraphPin* Old = FindPin(ValuePinName))
	{
		Old->BreakAllPinLinks();
		RemovePin(Old);
	}
	ValueKind = NewKind;
	CreateValuePin();

	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
	if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_SetIndexedPrimitiveData::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin)
	{
		return;
	}

	if (Pin->PinName == IndexPinName)
	{
		Modify();

		// A new index: keep the current parameter if the new index has it too (swapping between two
		// indexes that share a layout should not lose the choice), otherwise take the first one, so
		// the node is immediately usable rather than showing an empty dropdown.
		const UPrimitiveDataIndex* Index = GetIndex();
		const FPrimitiveDataIndexEntry* Entry = ResolveParameter();
		if (!Entry && Index && Index->Parameters.Num() > 0)
		{
			Entry = &Index->Parameters[0];
		}

		ParameterId = Entry ? Entry->Id : FGuid();
		ParameterName = Entry ? Entry->Name : NAME_None;
		if (UEdGraphPin* ParameterPin = FindPin(ParameterPinName))
		{
			ParameterPin->DefaultValue = ParameterName.IsNone() ? FString() : ParameterName.ToString();
		}
		SetValueKind(KindOf(Entry));
	}
	else if (Pin->PinName == ParameterPinName)
	{
		Modify();
		const UPrimitiveDataIndex* Index = GetIndex();
		const FPrimitiveDataIndexEntry* Entry = Index ? Index->FindParameter(FName(*Pin->DefaultValue)) : nullptr;
		ParameterId = Entry ? Entry->Id : FGuid();
		ParameterName = Entry ? Entry->Name : NAME_None;
		SetValueKind(KindOf(Entry));
	}
}

void UK2Node_SetIndexedPrimitiveData::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// The new pins get their defaults copied over only AFTER this returns, so the index has to be read
	// off the old ones - and loaded, since reconstruction can run while the Blueprint itself is loading.
	if (UPrimitiveDataIndex* Index = GetIndex(&OldPins))
	{
		PreloadObject(Index);
	}
	RefreshSelection(&OldPins);

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

void UK2Node_SetIndexedPrimitiveData::PostReconstructNode()
{
	Super::PostReconstructNode();

	// Reconstruction copied the OLD name back onto the pin. If the parameter was relabelled in the
	// index since, the GUID found it under its new name; show that one.
	if (!ParameterName.IsNone())
	{
		if (UEdGraphPin* ParameterPin = FindPin(ParameterPinName))
		{
			ParameterPin->DefaultValue = ParameterName.ToString();
		}
	}
}

UK2Node::ERedirectType UK2Node_SetIndexedPrimitiveData::DoPinsMatchForReconstruction(const UEdGraphPin* NewPin,
	int32 NewPinIndex, const UEdGraphPin* OldPin, int32 OldPinIndex) const
{
	static const FName LegacyTargetPinName(TEXT("Target"));
	if (NewPin && OldPin && NewPin->PinName == TargetPinName && OldPin->PinName == LegacyTargetPinName
		&& NewPin->Direction == OldPin->Direction)
	{
		return ERedirectType_Name;
	}
	return Super::DoPinsMatchForReconstruction(NewPin, NewPinIndex, OldPin, OldPinIndex);
}

void UK2Node_SetIndexedPrimitiveData::PreloadRequiredAssets()
{
	// Blueprints compile on load in the editor; ExpandNode reads the index, so it has to be in memory.
	if (UPrimitiveDataIndex* Index = GetIndex())
	{
		PreloadObject(Index);
	}
	Super::PreloadRequiredAssets();
}

