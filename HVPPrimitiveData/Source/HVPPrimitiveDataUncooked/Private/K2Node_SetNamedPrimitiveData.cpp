FText UK2Node_SetNamedPrimitiveData::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (TitleType == ENodeTitleType::FullTitle && !ParameterName.IsNone())
	{
		if (const UPrimitiveDataLegend* Legend = GetLegend())
		{
			// Second line is the legend, the way a function node shows its target class.
			return FText::Format(bWriteDefaults
					? LOCTEXT("DefaultTitleWithParameter", "Set Default {0}\n{1}")
					: LOCTEXT("TitleWithParameter", "Set {0}\n{1}"),
				FText::FromName(ParameterName), FText::FromString(Legend->GetName()));
		}
	}
	return bWriteDefaults ? LOCTEXT("DefaultTitle", "Set Named Primitive Data Defaults") : LOCTEXT("Title", "Set Named Primitive Data");
}

FText UK2Node_SetNamedPrimitiveData::GetTooltipText() const
{
	return LOCTEXT("Tooltip",
		"Set one custom primitive data parameter on a mesh, chosen by name from a Primitive Data Legend.\n\n"
		"Compiles to SetCustomPrimitiveDataFloat / SetCustomPrimitiveDataVector4 with the slot baked in, "
		"so it costs the same as the hand-wired call.\n\n"
		"Write Defaults (Details panel) sets the Custom Primitive Data Defaults instead, which are saved with the "
		"mesh - use it in construction scripts, where runtime data does not survive the level loading. It rebuilds "
		"the mesh's render state, so not every frame.");
}

