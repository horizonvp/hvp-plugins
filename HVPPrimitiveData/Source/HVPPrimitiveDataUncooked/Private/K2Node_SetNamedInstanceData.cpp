// A self pin, so several meshes or an array can be wired in - see UK2Node_SetNamedPrimitiveData.
const FName UK2Node_SetNamedInstanceData::TargetPinName(UEdGraphSchema_K2::PN_Self);
const FName UK2Node_SetNamedInstanceData::InstanceIndexPinName(TEXT("InstanceIndex"));
const FName UK2Node_SetNamedInstanceData::LegendPinName(TEXT("Legend"));
const FName UK2Node_SetNamedInstanceData::ParameterPinName(TEXT("Parameter"));
const FName UK2Node_SetNamedInstanceData::ValuePinName(TEXT("Value"));
const FName UK2Node_SetNamedInstanceData::MarkRenderStateDirtyPinName(TEXT("bMarkRenderStateDirty"));

namespace SetNamedInstanceData
{
	const TCHAR* DefaultColor = TEXT("(R=1.000000,G=1.000000,B=1.000000,A=1.000000)");
	const TCHAR* DefaultScalar = TEXT("0.0");
}

