FText UK2Node_SetIndexedPrimitiveData::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (TitleType == ENodeTitleType::FullTitle && !ParameterName.IsNone())
	{
		if (const UPrimitiveDataIndex* Index = GetIndex())
		{
			// Second line is the index, the way a function node shows its target class.
			return FText::Format(LOCTEXT("TitleWithParameter", "Set {0}\n{1}"),
				FText::FromName(ParameterName), FText::FromString(Index->GetName()));
		}
	}
	return LOCTEXT("Title", "Set Indexed Primitive Data");
}

FText UK2Node_SetIndexedPrimitiveData::GetTooltipText() const
{
	return LOCTEXT("Tooltip",
		"Set one custom primitive data parameter on a mesh, chosen by name from a Primitive Data Index.\n\n"
		"Compiles to SetCustomPrimitiveDataFloat / SetCustomPrimitiveDataVector4 with the slot baked in, "
		"so it costs the same as the hand-wired call.");
}

FSlateIcon UK2Node_SetIndexedPrimitiveData::GetIconAndTint(FLinearColor& OutColor) const
{
	static const FSlateIcon Icon(FAppStyle::GetAppStyleSetName(), TEXT("Kismet.AllClasses.FunctionIcon"));
	return Icon;
}

void UK2Node_SetIndexedPrimitiveData::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	UClass* ActionKey = GetClass();
	if (ActionRegistrar.IsOpenForRegistration(ActionKey))
	{
		UBlueprintNodeSpawner* Spawner = UBlueprintNodeSpawner::Create(ActionKey);
		check(Spawner);
		ActionRegistrar.AddBlueprintAction(ActionKey, Spawner);
	}
}

FText UK2Node_SetIndexedPrimitiveData::GetMenuCategory() const
{
	// Beside the engine's own SetCustomPrimitiveData* functions.
	return LOCTEXT("Category", "Rendering|Material");
}

