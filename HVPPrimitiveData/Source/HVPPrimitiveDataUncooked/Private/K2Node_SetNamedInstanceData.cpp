// Pins
// ---------------------------------------------------------------------------

void UK2Node_SetNamedInstanceData::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* Target = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UInstancedStaticMeshComponent::StaticClass(), TargetPinName);
	Target->PinFriendlyName = LOCTEXT("TargetName", "Target");
	Target->PinToolTip = LOCTEXT("TargetTooltip",
		"The instanced static mesh to set the data on. Wire in several, or an array, to set the same instance on each.").ToString();

	UEdGraphPin* Instance = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Int, InstanceIndexPinName);
	Instance->PinToolTip = LOCTEXT("InstanceTooltip", "Which instance to set the data on.").ToString();
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Instance, TEXT("0"));

	// Choices made on the node, not data: only the default-value widget is left.
	UEdGraphPin* Legend = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UInstanceDataLegend::StaticClass(), LegendPinName);
	Legend->bNotConnectable = true;
	Legend->PinToolTip = LOCTEXT("LegendTooltip", "The Instance Data Legend that names the parameters.").ToString();

	UEdGraphPin* Parameter = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, ParameterPinName);
	Parameter->bNotConnectable = true;
	Parameter->PinToolTip = LOCTEXT("ParameterTooltip", "Which of the legend's parameters to set.").ToString();

	CreateValuePin();

	// The engine call's own option, tucked away as the engine tucks it.
	UEdGraphPin* Dirty = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, MarkRenderStateDirtyPinName);
	Dirty->PinFriendlyName = LOCTEXT("DirtyName", "Mark Render State Dirty");
	Dirty->PinToolTip = LOCTEXT("DirtyTooltip",
		"Rebuild the mesh's render state now. Not needed for the change to show; expensive, so not every frame.").ToString();
	Dirty->bAdvancedView = true;
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Dirty, TEXT("false"));
	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	Super::AllocateDefaultPins();
}

void UK2Node_SetNamedInstanceData::CreateValuePin()
{
	UEdGraphPin* Value = nullptr;
	switch (ValueKind)
	{
	case ENamedPrimitiveDataValueKind::Scalar:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, ValuePinName);
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetNamedInstanceData::DefaultScalar);
		break;
	case ENamedPrimitiveDataValueKind::Vector:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, TBaseStructure<FLinearColor>::Get(), ValuePinName);
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, SetNamedInstanceData::DefaultColor);
		Value->PinToolTip = LOCTEXT("VectorTooltip", "Red, green and blue go to the three floats; alpha is not stored.").ToString();
		break;
	default:
		// No parameter chosen: no Value pin, rather than a wildcard that would accept anything and then fail.
		break;
	}
}

UEdGraphPin* UK2Node_SetNamedInstanceData::FindPinIn(FName Name, const TArray<UEdGraphPin*>* InPins) const
{
	const TArray<UEdGraphPin*>& Search = InPins ? *InPins : Pins;
	for (UEdGraphPin* Pin : Search)
	{
		if (Pin && Pin->PinName == Name)
		{
			return Pin;
		}
	}
	return nullptr;
}

UInstanceDataLegend* UK2Node_SetNamedInstanceData::GetLegend(const TArray<UEdGraphPin*>* InPins) const
{
	const UEdGraphPin* Pin = FindPinIn(LegendPinName, InPins);
	return Pin ? Cast<UInstanceDataLegend>(Pin->DefaultObject) : nullptr;
}

const FInstanceDataLegendEntry* UK2Node_SetNamedInstanceData::ResolveParameter(const TArray<UEdGraphPin*>* InPins) const
{
	const UInstanceDataLegend* Legend = GetLegend(InPins);
	if (!Legend)
	{
		return nullptr;
	}
	if (const FInstanceDataLegendEntry* ById = Legend->FindParameter(ParameterId))
	{
		return ById;
	}
	const UEdGraphPin* Pin = FindPinIn(ParameterPinName, InPins);
	return Pin ? Legend->FindParameter(FName(*Pin->DefaultValue)) : nullptr;
}

ENamedPrimitiveDataValueKind UK2Node_SetNamedInstanceData::KindOf(const FInstanceDataLegendEntry* Entry)
{
	if (!Entry)
	{
		return ENamedPrimitiveDataValueKind::None;
	}
	return Entry->Type == EInstanceDataParameterType::Vector
		? ENamedPrimitiveDataValueKind::Vector
		: ENamedPrimitiveDataValueKind::Scalar;
}

void UK2Node_SetNamedInstanceData::RefreshSelection(const TArray<UEdGraphPin*>* InPins)
{
	const FInstanceDataLegendEntry* Entry = ResolveParameter(InPins);
	if (Entry)
	{
		ParameterId = Entry->Id;
		ParameterName = Entry->Name;
	}
	// A selection the legend no longer has keeps its GUID, so an undo in the legend brings it back; the
	// kind still drops, so the node cannot compile against a type that is no longer there.
	ValueKind = KindOf(Entry);
}

void UK2Node_SetNamedInstanceData::SetValueKind(ENamedPrimitiveDataValueKind NewKind)
{
	if (NewKind == ValueKind)
	{
		return;
	}

	Modify();
	if (UEdGraphPin* Old = FindPin(ValuePinName))
	{
		Old->BreakAllPinLinks();
		RemovePin(Old);
	}
	ValueKind = NewKind;
	CreateValuePin();

	// CreatePin appends; put Value back above the advanced pin, where AllocateDefaultPins makes it.
	if (UEdGraphPin* Value = FindPin(ValuePinName))
	{
		const int32 DirtyIndex = Pins.IndexOfByPredicate([](const UEdGraphPin* Pin) { return Pin->PinName == MarkRenderStateDirtyPinName; });
		if (DirtyIndex != INDEX_NONE)
		{
			Pins.Remove(Value);
			Pins.Insert(Value, DirtyIndex);
		}
	}

	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
	if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_SetNamedInstanceData::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin)
	{
		return;
	}

	if (Pin->PinName == LegendPinName)
	{
		Modify();

		// Keep the current parameter if the new legend has it too, otherwise take the first one.
		const UInstanceDataLegend* Legend = GetLegend();
		const FInstanceDataLegendEntry* Entry = ResolveParameter();
		if (!Entry && Legend && Legend->Parameters.Num() > 0)
		{
			Entry = &Legend->Parameters[0];
		}

		ParameterId = Entry ? Entry->Id : FGuid();
		ParameterName = Entry ? Entry->Name : NAME_None;
		if (UEdGraphPin* ParameterPin = FindPin(ParameterPinName))
		{
			ParameterPin->DefaultValue = ParameterName.IsNone() ? FString() : ParameterName.ToString();
		}
		SetValueKind(KindOf(Entry));
	}
	else if (Pin->PinName == ParameterPinName)
	{
		Modify();
		const UInstanceDataLegend* Legend = GetLegend();
		const FInstanceDataLegendEntry* Entry = Legend ? Legend->FindParameter(FName(*Pin->DefaultValue)) : nullptr;
		ParameterId = Entry ? Entry->Id : FGuid();
		ParameterName = Entry ? Entry->Name : NAME_None;
		SetValueKind(KindOf(Entry));
	}
}

void UK2Node_SetNamedInstanceData::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// The new pins get their defaults only after this returns: read the legend off the old ones.
	if (UInstanceDataLegend* Legend = GetLegend(&OldPins))
	{
		PreloadObject(Legend);
	}
	RefreshSelection(&OldPins);

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

void UK2Node_SetNamedInstanceData::PostReconstructNode()
{
	Super::PostReconstructNode();

	// Reconstruction copied the OLD name back onto the pin; show the one the GUID found.
	if (!ParameterName.IsNone())
	{
		if (UEdGraphPin* ParameterPin = FindPin(ParameterPinName))
		{
			ParameterPin->DefaultValue = ParameterName.ToString();
		}
	}
}

void UK2Node_SetNamedInstanceData::PreloadRequiredAssets()
{
	if (UInstanceDataLegend* Legend = GetLegend())
	{
		PreloadObject(Legend);
	}
	Super::PreloadRequiredAssets();
}

