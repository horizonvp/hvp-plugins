FName UK2Node_SetNamedInstanceDataBatch::PinNameFor(const FGuid& Id)
{
	return FName(*FString::Printf(TEXT("Param_%s"), *Id.ToString(EGuidFormats::Digits)));
}

void UK2Node_SetNamedInstanceDataBatch::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* Target = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UInstancedStaticMeshComponent::StaticClass(), TargetPinName);
	Target->PinFriendlyName = LOCTEXT("TargetName", "Target");
	Target->PinToolTip = LOCTEXT("TargetTooltip",
		"The instanced static mesh to set the data on. Wire in several, or an array, to set the same instances on each.").ToString();

	FCreatePinParams ArrayParams;
	ArrayParams.ContainerType = EPinContainerType::Array;
	UEdGraphPin* Instances = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Int, InstanceIndicesPinName, ArrayParams);
	Instances->PinToolTip = LOCTEXT("InstancesTooltip",
		"The instances to set. Per instance parameters take their k-th value for the k-th index here. Consecutive "
		"ascending indices are written as one block, the fastest case.").ToString();

	UEdGraphPin* Legend = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UInstanceDataLegend::StaticClass(), LegendPinName);
	Legend->bNotConnectable = true;
	Legend->PinToolTip = LOCTEXT("LegendTooltip",
		"The Instance Data Legend that names the parameters. Tick the ones to set, and which take a value per instance, in the Details panel.").ToString();

	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		CreateValuePin(Selected);
	}

	UEdGraphPin* Dirty = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Boolean, MarkRenderStateDirtyPinName);
	Dirty->PinFriendlyName = LOCTEXT("DirtyName", "Mark Render State Dirty");
	Dirty->PinToolTip = LOCTEXT("DirtyTooltip",
		"Rebuild the mesh's render state now. Not needed for the change to show; expensive, so not every frame.").ToString();
	Dirty->bAdvancedView = true;
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Dirty, TEXT("false"));
	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	Super::AllocateDefaultPins();
}

void UK2Node_SetNamedInstanceDataBatch::CreateValuePin(const FNamedInstanceDataBatchSelection& Selected)
{
	FCreatePinParams Params;
	Params.ContainerType = Selected.bPerInstance ? EPinContainerType::Array : EPinContainerType::None;

	UEdGraphPin* Value = nullptr;
	switch (Selected.Kind)
	{
	case ENamedPrimitiveDataValueKind::Scalar:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PinNameFor(Selected.Id), Params);
		break;
	case ENamedPrimitiveDataValueKind::Vector:
		Value = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, TBaseStructure<FLinearColor>::Get(), PinNameFor(Selected.Id), Params);
		break;
	default:
		// No longer in the legend: no pin, and validation says why.
		return;
	}
	if (!Selected.bPerInstance)
	{
		GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Value, Selected.Kind == ENamedPrimitiveDataValueKind::Vector
			? SetNamedInstanceDataBatch::DefaultColor : SetNamedInstanceDataBatch::DefaultScalar);
	}
	Value->PinFriendlyName = Selected.bPerInstance
		? FText::Format(LOCTEXT("PerInstanceName", "{0} (per instance)"), FText::FromName(Selected.Name))
		: FText::FromName(Selected.Name);
}

void UK2Node_SetNamedInstanceDataBatch::PostReconstructNode()
{
	Super::PostReconstructNode();

	const UInstanceDataLegend* Legend = GetLegend();
	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		UEdGraphPin* Value = FindValuePin(Selected.Id);
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Value && Entry && Entry->HasSlot())
		{
			const FString Slots = Entry->GetWidth() > 1
				? FString::Printf(TEXT("slots %d-%d; alpha is not stored"), Entry->Slot, Entry->Slot + Entry->GetWidth() - 1)
				: FString::Printf(TEXT("slot %d"), Entry->Slot);
			Value->PinToolTip = Selected.bPerInstance
				? FString::Printf(TEXT("%s (%s). One value per entry of Instance Indices; instances past the end of this array keep theirs."),
					*Selected.Name.ToString(), *Slots)
				: FString::Printf(TEXT("%s (%s). The same value for every instance."), *Selected.Name.ToString(), *Slots);
		}
	}
}

UEdGraphPin* UK2Node_SetNamedInstanceDataBatch::FindPinIn(FName Name, const TArray<UEdGraphPin*>* InPins) const
{
	const TArray<UEdGraphPin*>& Search = InPins ? *InPins : Pins;
	for (UEdGraphPin* Pin : Search)
	{
		if (Pin && Pin->PinName == Name)
		{
			return Pin;
		}
	}
	return nullptr;
}

UEdGraphPin* UK2Node_SetNamedInstanceDataBatch::FindValuePin(const FGuid& Id) const
{
	return FindPinIn(PinNameFor(Id), nullptr);
}

UInstanceDataLegend* UK2Node_SetNamedInstanceDataBatch::GetLegend(const TArray<UEdGraphPin*>* InPins) const
{
	const UEdGraphPin* Pin = FindPinIn(LegendPinName, InPins);
	return Pin ? Cast<UInstanceDataLegend>(Pin->DefaultObject) : nullptr;
}

const FInstanceDataLegendEntry* UK2Node_SetNamedInstanceDataBatch::Resolve(const UInstanceDataLegend* Legend,
	const FNamedInstanceDataBatchSelection& Selected) const
{
	if (!Legend)
	{
		return nullptr;
	}
	if (const FInstanceDataLegendEntry* ById = Legend->FindParameter(Selected.Id))
	{
		return ById;
	}
	return Selected.Name.IsNone() ? nullptr : Legend->FindParameter(Selected.Name);
}

// ---------------------------------------------------------------------------
// Selection
// ---------------------------------------------------------------------------

bool UK2Node_SetNamedInstanceDataBatch::IsParameterSelected(const FGuid& Id) const
{
	return Selection.ContainsByPredicate([&Id](const FNamedInstanceDataBatchSelection& Selected) { return Selected.Id == Id; });
}

void UK2Node_SetNamedInstanceDataBatch::SetParameterSelected(const FGuid& Id, bool bSelected)
{
	if (IsParameterSelected(Id) == bSelected)
	{
		return;
	}

	Modify();
	if (bSelected)
	{
		Selection.AddDefaulted_GetRef().Id = Id;
	}
	else
	{
		Selection.RemoveAll([&Id](const FNamedInstanceDataBatchSelection& Selected) { return Selected.Id == Id; });
		DropValuePin(Id);
	}
	RefreshSelection(nullptr);
	Rebuild();
}

bool UK2Node_SetNamedInstanceDataBatch::IsParameterPerInstance(const FGuid& Id) const
{
	const FNamedInstanceDataBatchSelection* Found =
		Selection.FindByPredicate([&Id](const FNamedInstanceDataBatchSelection& Selected) { return Selected.Id == Id; });
	return Found && Found->bPerInstance;
}

void UK2Node_SetNamedInstanceDataBatch::SetParameterPerInstance(const FGuid& Id, bool bPerInstance)
{
	FNamedInstanceDataBatchSelection* Found =
		Selection.FindByPredicate([&Id](const FNamedInstanceDataBatchSelection& Selected) { return Selected.Id == Id; });
	if (!Found || Found->bPerInstance == bPerInstance)
	{
		return;
	}

	Modify();
	Found->bPerInstance = bPerInstance;
	// The pin changes type: a single value's wire cannot carry over to an array, or back.
	DropValuePin(Id);
	Rebuild();
}

void UK2Node_SetNamedInstanceDataBatch::DropValuePin(const FGuid& Id)
{
	if (UEdGraphPin* Pin = FindValuePin(Id))
	{
		Pin->BreakAllPinLinks();
		RemovePin(Pin);
	}
}

void UK2Node_SetNamedInstanceDataBatch::RefreshSelection(const TArray<UEdGraphPin*>* InPins)
{
	const UInstanceDataLegend* Legend = GetLegend(InPins);
	if (!Legend)
	{
		return;
	}

	for (FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry)
		{
			Selected.Id = Entry->Id;
			Selected.Name = Entry->Name;
		}
		Selected.Kind = SetNamedInstanceDataBatch::KindOf(Entry);
	}

	auto IndexOf = [Legend](const FNamedInstanceDataBatchSelection& Selected)
	{
		const int32 Index = Legend->Parameters.IndexOfByPredicate(
			[&Selected](const FInstanceDataLegendEntry& Entry) { return Entry.Id == Selected.Id; });
		return Index == INDEX_NONE ? MAX_int32 : Index;
	};
	Selection.StableSort([&IndexOf](const FNamedInstanceDataBatchSelection& A, const FNamedInstanceDataBatchSelection& B)
	{
		return IndexOf(A) < IndexOf(B);
	});
}

void UK2Node_SetNamedInstanceDataBatch::Rebuild()
{
	ReconstructNode();
	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyNodeChanged(this);
	}
	if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_SetNamedInstanceDataBatch::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin || Pin->PinName != LegendPinName)
	{
		return;
	}

	Modify();
	const UInstanceDataLegend* Legend = GetLegend();
	Selection.RemoveAll([this, Legend](const FNamedInstanceDataBatchSelection& Selected)
	{
		if (Resolve(Legend, Selected))
		{
			return false;
		}
		DropValuePin(Selected.Id);
		return true;
	});
	RefreshSelection(nullptr);
	Rebuild();
	OnParametersOffered.Broadcast();
}

void UK2Node_SetNamedInstanceDataBatch::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	if (UInstanceDataLegend* Legend = GetLegend(&OldPins))
	{
		PreloadObject(Legend);
	}
	RefreshSelection(&OldPins);

	Super::ReallocatePinsDuringReconstruction(OldPins);
}

UK2Node::ERedirectType UK2Node_SetNamedInstanceDataBatch::DoPinsMatchForReconstruction(const UEdGraphPin* NewPin,
	int32 NewPinIndex, const UEdGraphPin* OldPin, int32 OldPinIndex) const
{
	if (NewPin && OldPin && NewPin->Direction == OldPin->Direction && NewPin->PinName == OldPin->PinName)
	{
		// A parameter whose type changed in the legend, or that switched between one value and an array.
		const bool bSameType = NewPin->PinType.PinCategory == OldPin->PinType.PinCategory
			&& NewPin->PinType.PinSubCategoryObject == OldPin->PinType.PinSubCategoryObject
			&& NewPin->PinType.ContainerType == OldPin->PinType.ContainerType;
		if (!bSameType)
		{
			return ERedirectType_None;
		}
	}
	return Super::DoPinsMatchForReconstruction(NewPin, NewPinIndex, OldPin, OldPinIndex);
}

void UK2Node_SetNamedInstanceDataBatch::PreloadRequiredAssets()
{
	if (UInstanceDataLegend* Legend = GetLegend())
	{
		PreloadObject(Legend);
	}
	Super::PreloadRequiredAssets();
}

bool UK2Node_SetNamedInstanceDataBatch::GetWriteRange(int32& OutFirst, int32& OutCount, uint64& OutMask) const
{
	OutFirst = 0;
	OutCount = 0;
	OutMask = 0;

	const UInstanceDataLegend* Legend = GetLegend();
	int32 First = MAX_int32;
	int32 End = 0;
	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry && Entry->HasSlot())
		{
			First = FMath::Min(First, Entry->Slot);
			End = FMath::Max(End, Entry->Slot + Entry->GetWidth());
		}
	}
	if (First == MAX_int32)
	{
		return false;
	}

	for (const FNamedInstanceDataBatchSelection& Selected : Selection)
	{
		const FInstanceDataLegendEntry* Entry = Resolve(Legend, Selected);
		if (Entry && Entry->HasSlot())
		{
			for (int32 Float = 0; Float < Entry->GetWidth(); ++Float)
			{
				OutMask |= uint64(1) << (Entry->Slot - First + Float);
			}
		}
	}
	OutFirst = First;
	OutCount = End - First;
	return true;
}

