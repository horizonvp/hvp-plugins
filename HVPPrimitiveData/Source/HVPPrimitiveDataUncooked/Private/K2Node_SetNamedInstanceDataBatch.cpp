const FName UK2Node_SetNamedInstanceDataBatch::TargetPinName(UEdGraphSchema_K2::PN_Self);
const FName UK2Node_SetNamedInstanceDataBatch::InstanceIndicesPinName(TEXT("InstanceIndices"));
const FName UK2Node_SetNamedInstanceDataBatch::LegendPinName(TEXT("Legend"));
const FName UK2Node_SetNamedInstanceDataBatch::MarkRenderStateDirtyPinName(TEXT("bMarkRenderStateDirty"));

namespace SetNamedInstanceDataBatch
{
	const TCHAR* DefaultColor = TEXT("(R=1.000000,G=1.000000,B=1.000000,A=1.000000)");
	const TCHAR* DefaultScalar = TEXT("0.0");

	ENamedPrimitiveDataValueKind KindOf(const FInstanceDataLegendEntry* Entry)
	{
		if (!Entry)
		{
			return ENamedPrimitiveDataValueKind::None;
		}
		return Entry->Type == EInstanceDataParameterType::Vector
			? ENamedPrimitiveDataValueKind::Vector
			: ENamedPrimitiveDataValueKind::Scalar;
	}
}

